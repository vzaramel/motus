#!/usr/bin/env node

import { fileURLToPath } from 'url';
import path from 'path';
import { mkdir, readFile, writeFile } from 'fs/promises';
import { existsSync } from 'fs';
import { spawnSync } from 'child_process';
import { buildBytecodeDebugSourceMap, extractBytecodeDebugMetadata } from './edge/src/bytecode-debug.js';

const __filename = fileURLToPath(import.meta.url);
const EXAMPLE_DIR = path.dirname(__filename);
const REPO_ROOT = path.resolve(EXAMPLE_DIR, '..');

const MANIFEST_PATH = path.join(EXAMPLE_DIR, 'system-components.txt');
const OUTPUT_BYTECODE_PATH = path.join(EXAMPLE_DIR, 'edge', 'src', 'system-components.generated.js');
const MAP_MODULE_PATH = path.join(EXAMPLE_DIR, 'edge', 'src', 'system-components.maps.generated.js');
const MAPS_DIR = path.join(EXAMPLE_DIR, 'edge', 'debug-maps');
const TMP_DIR = path.join(EXAMPLE_DIR, '.tmp', 'system-components');

const MOT_BIN = path.join(REPO_ROOT, 'build', 'mot');

function toBase64(uint8) {
  return Buffer.from(uint8).toString('base64');
}

function readManifestLines(text) {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'));
}

function runChecked(bin, args, cwd, label) {
  const result = spawnSync(bin, args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) {
    throw new Error(`${label} failed: ${bin} ${args.join(' ')}`);
  }
}

function ensureBinaries() {
  if (existsSync(MOT_BIN)) return;
  runChecked('make', ['cli'], REPO_ROOT, 'build tools');
  if (!existsSync(MOT_BIN)) {
    throw new Error('Required binary not found after build (build/mot)');
  }
}

function renderBytecodeModule(components) {
  const header = [
    '/*',
    ' * AUTO-GENERATED FILE. DO NOT EDIT.',
    ' *',
    ' * Generated by `example/precompile-system-components.mjs`.',
    ' */',
    '',
    'export const SYSTEM_COMPONENTS = {',
  ];
  const lines = components.map(({ path: compPath, base64 }) =>
    `  ${JSON.stringify(compPath)}: ${JSON.stringify(base64)},`);
  return [...header, ...lines, '};', ''].join('\n');
}

function renderMapModule(componentMaps) {
  const header = [
    '/*',
    ' * AUTO-GENERATED FILE. DO NOT EDIT.',
    ' *',
    ' * Generated by `example/precompile-system-components.mjs`.',
    ' */',
    '',
    'export const SYSTEM_COMPONENT_SOURCE_MAPS = {',
  ];
  const lines = componentMaps.map(({ path: compPath, sourceMap }) =>
    `  ${JSON.stringify(compPath)}: ${JSON.stringify(sourceMap)},`);
  return [...header, ...lines, '};', ''].join('\n');
}

async function main() {
  ensureBinaries();

  const manifestText = await readFile(MANIFEST_PATH, 'utf8');
  const componentPaths = readManifestLines(manifestText);
  if (componentPaths.length === 0) {
    throw new Error(`No components listed in ${MANIFEST_PATH}`);
  }

  await mkdir(TMP_DIR, { recursive: true });
  await mkdir(MAPS_DIR, { recursive: true });

  const bytecodeArtifacts = [];
  const mapArtifacts = [];

  for (const rawPath of componentPaths) {
    const logicalPath = rawPath.endsWith('.mot') ? rawPath.slice(0, -4) : rawPath;
    const sourcePath = path.join(EXAMPLE_DIR, 'content', `${logicalPath}.mot`);
    const routeName = logicalPath.replace(/^components\//, '');
    const safeName = logicalPath.replace(/[\\/]/g, '__');
    const bytecodePath = path.join(TMP_DIR, `${safeName}.bc`);

    runChecked(
      MOT_BIN,
      [
        '--input', sourcePath,
        '--target', 'bytecode',
        '--bytecode-out', bytecodePath,
        '--linked-manifest', MANIFEST_PATH,
      ],
      REPO_ROOT,
      `compile ${logicalPath}`,
    );
    const bytecode = new Uint8Array(await readFile(bytecodePath));
    bytecodeArtifacts.push({ path: logicalPath, base64: toBase64(bytecode) });

    const debugMeta = extractBytecodeDebugMetadata(bytecode);
    const sourceMap = buildBytecodeDebugSourceMap(debugMeta, {
      file: `${routeName}.wasm`,
      source: `${logicalPath}.mot`,
    });
    if (sourceMap) {
      mapArtifacts.push({ path: logicalPath, sourceMap });
      await writeFile(path.join(MAPS_DIR, `${safeName}.map.json`), JSON.stringify(sourceMap), 'utf8');
    }

    console.log(`[precompile] ${logicalPath}: bytecode=${bytecode.length}B`);
  }

  await writeFile(OUTPUT_BYTECODE_PATH, renderBytecodeModule(bytecodeArtifacts), 'utf8');
  await writeFile(MAP_MODULE_PATH, renderMapModule(mapArtifacts), 'utf8');

  console.log(`[precompile] Wrote ${OUTPUT_BYTECODE_PATH} (${bytecodeArtifacts.length} components)`);
  console.log(`[precompile] Wrote ${MAP_MODULE_PATH} (${mapArtifacts.length} maps)`);
}

main().catch((err) => {
  console.error(`[precompile] ${err?.message || String(err)}`);
  process.exit(1);
});
